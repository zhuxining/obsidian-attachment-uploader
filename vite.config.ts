import { copyFile } from "node:fs/promises";
import { builtinModules } from "node:module";
import { resolve } from "node:path";

import { defineConfig } from "vite-plus";

const externalModules = new Set([...builtinModules, "obsidian", "electron"]);

export default defineConfig(({ mode }) => ({
  plugins: [
    {
      name: "obsidian-plugin-output",
      apply: "build",
      async writeBundle(options) {
        // Obsidian and the release workflow load main.js from the project root.
        await copyFile(resolve(options.dir ?? "dist", "main.js"), resolve("main.js"));
      },
    },
  ],
  build: {
    lib: {
      entry: "src/main.ts",
      formats: ["cjs"],
      fileName: () => "main.js",
    },
    outDir: "dist",
    emptyOutDir: true,
    copyPublicDir: false,
    target: "es2022",
    minify: false,
    sourcemap: mode === "development" ? "inline" : false,
    rolldownOptions: {
      external: (id) =>
        externalModules.has(id) ||
        id.startsWith("node:") ||
        id.startsWith("@codemirror/") ||
        id.startsWith("@lezer/"),
      output: {
        exports: "default",
        codeSplitting: false,
        banner: "/* Generated by Vite Plus / Rolldown. Source: src/main.ts */",
      },
    },
  },
  staged: {
    "*": "vp check --fix",
  },
  fmt: {
    sortImports: true,
  },
  lint: {
    jsPlugins: [{ name: "vite-plus", specifier: "vite-plus/oxlint-plugin" }],
    rules: {
      "vite-plus/prefer-vite-plus-imports": "error",
      "typescript/no-deprecated": "error",
    },
    options: { typeAware: true, typeCheck: true },
    plugins: ["import", "promise", "vitest", "node"],
  },
  test: {
    environment: "node",
    include: ["tests/**/*.test.ts"],
  },
  run: {
    tasks: {
      ci: "npm run build",
    },
  },
}));
